//! Cross-KATs extracted from the Zig tree (mac_test.zig / noise_test.zig,
//! "independently derived from Python"). These make the Rust port prove
//! byte-identity against the reference BEFORE any live traffic.
use bolina::transport::mac1::compute_mac1;
use bolina::transport::noise::SymmetricState;

fn ramp(n: u8) -> [u8; 32] { let mut a = [0u8; 32]; for (i, b) in a.iter_mut().enumerate() { *b = n.wrapping_add(i as u8); } a }

#[test]
fn zig_mac1_known_answer() {
    let responder = ramp(0);
    let msg = b"bolina-handshake-init-preceding-mac1";
    let want: [u8; 16] = [0xb0,0x1d,0x8e,0xbc,0x37,0x49,0x47,0x5d,0x9c,0xb9,0x61,0xea,0x43,0xd6,0xe4,0xa6];
    assert_eq!(compute_mac1(&responder, msg), want, "mac1 diverges from Zig/Python KAT");
}

#[test]
fn zig_split_known_answer() {
    let mut s = SymmetricState::init();
    s.mix_key(&[0x33u8; 32]);
    let (c1, c2) = s.split();
    let want_c1 = [0x0c,0xea,0xe9,0xb4,0x13,0x3d,0xd8,0x9a,0xc6,0xf4,0x73,0xad,0x26,0x5f,0x86,0xa1,0x6d,0xc2,0xfc,0xc0,0x5a,0x20,0x89,0xdf,0x5a,0xbe,0x01,0x49,0x59,0x60,0xff,0x4a];
    let want_c2 = [0x4b,0x57,0x8d,0xe5,0x0b,0x39,0xce,0xbe,0x26,0x63,0x56,0x5d,0xbf,0x32,0xb8,0xa5,0x10,0xe0,0x31,0xd8,0xdd,0x85,0x33,0x00,0xa8,0x20,0x4b,0x84,0x0e,0xc3,0xfe,0xb6];
    assert_eq!(c1, want_c1, "c1 diverges");
    assert_eq!(c2, want_c2, "c2 diverges");
}

#[test]
fn rfc8439_aead_vector_rust_side() {
    use chacha20poly1305::{ChaCha20Poly1305, Key, Nonce, aead::{Aead, KeyInit}};
    let key = Key::from_slice(&[0x80,0x81,0x82,0x83,0x84,0x85,0x86,0x87,0x88,0x89,0x8a,0x8b,0x8c,0x8d,0x8e,0x8f,0x90,0x91,0x92,0x93,0x94,0x95,0x96,0x97,0x98,0x99,0x9a,0x9b,0x9c,0x9d,0x9e,0x9f]);
    let nonce = Nonce::from_slice(&[0x07,0x00,0x00,0x00,0x40,0x41,0x42,0x43,0x44,0x45,0x46,0x47]);
    let aad = [0x50,0x51,0x52,0x53,0xc0,0xc1,0xc2,0xc3,0xc4,0xc5,0xc6,0xc7];
    let pt = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";
    let ct = ChaCha20Poly1305::new(key).encrypt(nonce, chacha20poly1305::aead::Payload { msg: pt, aad: &aad }).unwrap();
    let want_head = "d31a8d34648e60db7b86afbc53ef7ec2a4aded51296e08fea9e2b5a736ee62d6";
    let got: String = ct.iter().map(|b| format!("{b:02x}")).collect();
    assert!(got.starts_with(&want_head), "rust aead ct diverges from RFC 8439: {got}");
    assert_eq!(&got[got.len()-32..], "1ae10b594f09e26a7e902ecbd0600691", "rust aead tag diverges");
}
